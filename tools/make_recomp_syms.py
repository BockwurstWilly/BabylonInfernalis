"""Write the N64Recomp symbol file (symbols_file_path mode) from the Ghidra function export.

Two executable sections, both static (no relocs):
  .boot  ROM 0x1000   -> 0x40000400, 0x4CC30 bytes
  .vm    ROM 0x4DC30  -> 0x41000000, 0xBE620 bytes
Function size = Ghidra body extent (entry .. body_max), so data islands between functions stay out.
usage: make_recomp_syms.py <functions.csv> <out.toml>
"""
import csv
import re
import sys

SECTIONS = [(".boot", "boot", 0x1000, 0x40000400, 0x4CC30), (".vm", "vm_paged", 0x4DC30, 0x41000000, 0xBE620)]
rows = list(csv.DictReader(open(sys.argv[1])))
ident = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
seen = set()
out = ["# Generated by tools/make_recomp_syms.py from analysis/functions.csv - do not edit by hand.", ""]
total = 0
for name, block, rom, vram, size in SECTIONS:
    fs = sorted((int(r["entry"], 16), int(r["body_max"], 16) + 1, r["name"]) for r in rows if r["block"] == block)
    # A function whose entry lies inside the previous function's extent is a shared tail Ghidra split off
    # (e.g. the part of __osException that handle_CpU branches into); N64Recomp needs disjoint functions.
    kept = []
    for f in fs:
        if kept and f[0] < kept[-1][1]:
            print(f"skipped {f[2]} {f[0]:08X}: inside {kept[-1][2]}")
            continue
        kept.append(f)
    fs = kept
    out += ["[[section]]", f'name = "{name}"', f"rom = 0x{rom:X}", f"vram = 0x{vram:X}", f"size = 0x{size:X}", "",
            "functions = ["]
    for (e, end, fname), nxt in zip(fs, fs[1:] + [(vram + size, 0, "")]):
        end = (end + 3) & ~3
        assert end <= nxt[0], f"{fname} overlaps the next function"
        assert vram <= e and end <= vram + size, f"{fname} outside its section"
        if not ident.match(fname) or fname in seen:
            raise SystemExit(f"bad or duplicate function name {fname!r} at {e:08X}")
        seen.add(fname)
        out.append(f'    {{ name = "{fname}", vram = 0x{e:08X}, size = 0x{end - e:X} }},')
    out += ["]", ""]
    total += len(fs)
open(sys.argv[2], "w", newline="\n").write("\n".join(out))
print("functions:", total)
