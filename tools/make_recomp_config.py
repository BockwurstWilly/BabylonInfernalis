"""Write recomp/indy64.recomp.toml = indy64.recomp.base.toml + generated instruction patches.

Generated:
- every `cache` instruction in a function that N64Recomp will translate becomes a nop (cache maintenance has no
  meaning natively; the Factor 5 memset/memcpy routines use "create dirty exclusive" before stores);
- every `bltzal $zero` (never branches, only sets $ra = pc+8; hand-written code uses it to find tables and snippets)
  with a nop delay slot becomes `lui ra, hi(pc+8)` / `ori ra, ra, lo(pc+8)`.
Functions that are stubbed in the base file or in N64Recomp's built-in libultra lists are skipped.
usage: make_recomp_config.py <rom> <recomp_dir> <symbol_lists.cpp>
"""
import os
import re
import struct
import sys

rom = open(sys.argv[1], "rb").read()
d = sys.argv[2]
base = open(os.path.join(d, "indy64.recomp.base.toml")).read()
syms = open(os.path.join(d, "indy64.syms.toml")).read()
lists = open(sys.argv[3], encoding="utf-8").read()

skip = set(re.findall(r'"(\w+)"', lists))
stubs = re.search(r"stubs = \[(.*?)\]", base, re.S)
skip |= set(re.findall(r'"(\w+)"', stubs.group(1))) if stubs else set()
secs = [(int(r, 16), int(v, 16)) for r, v in re.findall(r"rom = 0x([0-9A-F]+)\nvram = 0x([0-9A-F]+)", syms)]
funcs = re.findall(r'name = "(\w+)", vram = 0x([0-9A-F]+), size = 0x([0-9A-F]+)', syms)


def rom_of(va):
    r, v = max((s for s in secs if s[1] <= va), key=lambda s: s[1])
    return r + va - v


out = [base.rstrip(), "", "# ---- generated by tools/make_recomp_config.py ----"]


def patch(func, vram, value, comment):
    out.extend(["[[patches.instruction]]", f'func = "{func}"', f"vram = 0x{vram:08X}   # {comment}",
                f"value = 0x{value:08X}"])


def word(a):
    return struct.unpack_from(">I", rom, rom_of(a))[0]


n_cache = n_pc = 0
for name, va, size in funcs:
    if name in skip:
        continue
    va, size = int(va, 16), int(size, 16)
    fname = "recomp_entrypoint" if va == 0x40000400 else name
    for a in range(va, va + size, 4):
        w = word(a)
        if w >> 26 == 0x2F:
            patch(fname, a, 0, "cache -> nop")
            n_cache += 1
        elif w >> 16 == 0x0410:  # bltzal $zero
            if word(a + 4) != 0:
                raise SystemExit(f"bltzal $zero at {a:08X} has a non-nop delay slot")
            ra = a + 8
            patch(fname, a, 0x3C1F0000 | (ra >> 16), f"bltzal $zero -> lui ra, 0x{ra >> 16:04X}")
            patch(fname, a + 4, 0x37FF0000 | (ra & 0xFFFF), f"delay slot -> ori ra, ra, 0x{ra & 0xFFFF:04X}")
            n_pc += 1
open(os.path.join(d, "indy64.recomp.toml"), "w", newline="\n").write("\n".join(out) + "\n")
print("cache patches:", n_cache, " bltzal patches:", n_pc)
